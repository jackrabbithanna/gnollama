class FormattingTests(unittest.TestCase):
    def test_prices_per_million_keep_small_amounts_and_drop_idle_zeros(self):
        for per_token, shown in (('0.000000075', '0.075'), ('0.0000003', '0.30'), ('0.000000015', '0.015'),
                                 ('0.000003', '3'), ('0.000015', '15'), ('0.0000025', '2.50'),
                                 ('0.0000000833333333333333', '0.08333'), ('0.0000000015', '0.0015'),
                                 ('0.0123456789', '12350'), ('0', '0')):
            with self.subTest(price=per_token):
                self.assertEqual(amount(Decimal(per_token), 1_000_000), shown)
        self.assertEqual(amount(Decimal('0.014')), '0.014')

    def test_a_malformed_price_is_left_out_and_never_read_as_zero(self):
        table = {'prompt': '0.000001', 'completion': 'soon', 'image': '', 'audio': None, 'request': 0.5,
                 'web_search': 'NaN', 'internal_reasoning': 'Infinity', 'input_cache_read': '-1',
                 'overrides': [{'min_prompt_tokens': 272000, 'prompt': '0.000016'}]}
        self.assertEqual(prices({'pricing': table}), {'prompt': Decimal('0.000001')})
        # Half a price says nothing about what a request costs, and is not free.
        self.assertEqual(summary_parts({'pricing': table}), [])
        self.assertEqual(price_lines({'pricing': table}), ['Prompt: $1 per 1M tokens', NOTE])
        for missing in ({}, {'pricing': None}, {'pricing': []}, {'pricing': {}}, {'pricing': {'prompt': 'x'}}, None):
            with self.subTest(details=missing):
                self.assertEqual((prices(missing), price_lines(missing)), ({}, []))

    def test_free_means_every_price_is_zero(self):
        free = {'pricing': {'prompt': '0', 'completion': '0.000', 'input_cache_read': '0'}}
        self.assertEqual((summary_parts(free), price_lines(free)), (['Free'], ['Free', NOTE]))
        searching = {'pricing': {'prompt': '0', 'completion': '0', 'web_search': '0.01'}}
        self.assertEqual(summary_parts(searching), ['$0 / $0 per 1M tokens'])
        self.assertEqual(price_lines(searching), ['Prompt: $0 per 1M tokens', 'Completion: $0 per 1M tokens',
                                                  'Web search: $0.01 per search', NOTE])
        # A catalog says a price varies with a negative number, which is neither free nor a price.
        self.assertEqual(summary_parts({'pricing': {'prompt': '-1', 'completion': '-1'}}), [])

    def test_every_price_has_a_line_and_an_unknown_one_is_shown_as_given(self):
        table = {'prompt': '0.000003', 'completion': '0.000015', 'image': '0.000003', 'audio': '0.000003',
                 'input_audio_cache': '0.00000015', 'web_search': '0.014', 'internal_reasoning': '0.000015',
                 'input_cache_read': '0.00000015', 'input_cache_write': '0.0000000833333333333333',
                 'input_cache_write_1h': '0.000016', 'image_output': '0.00003', 'audio_output': '0.000064',
                 'request': '0', 'discount_rate': '0.25'}
        self.assertEqual(price_lines({'pricing': table}), [
            'Prompt: $3 per 1M tokens', 'Completion: $15 per 1M tokens', 'Cache read: $0.15 per 1M tokens',
            'Cache write: $0.08333 per 1M tokens', 'Cache write, kept one hour: $16 per 1M tokens',
            'Reasoning: $15 per 1M tokens', 'Image input: $3 per 1M tokens', 'Audio input: $3 per 1M tokens',
            'Cached audio input: $0.15 per 1M tokens', 'Image output: $30 per 1M tokens',
            'Audio output: $64 per 1M tokens', 'Web search: $0.014 per search', 'Discount rate: $0.25', NOTE])

    def test_context_sizes_read_as_people_say_them(self):
        for count, shown in ((512, '512'), (2048, '2K'), (8192, '8K'), (32768, '33K'), (128000, '128K'),
                             (131072, '131K'), (262144, '262K'), (524288, '524K'), (999499, '999K'),
                             (999500, '1M'), (1000000, '1M'), (1048576, '1M'), (1500000, '1.5M'), (2000000, '2M')):
            with self.subTest(count=count):
                self.assertEqual(token_count(count), shown)

    def test_parts_for_each_kind_of_model(self):
        listed = dict(SHOW, context_length=131072)
        cases = (
            ('ollama vision and tools', listed, ['Images', 'Tools', 'No thinking', '131K context']),
            ('ollama plain', {'capabilities': ['completion'], 'context_length': 8192},
             ['No images', 'No tools', 'No thinking', '8K context']),
            ('ollama before capabilities were reported', {'details': {'family': 'llama'}}, []),
            ('lm studio loaded', {'supports': {'vision': True, 'tools': True}, 'thinking_levels': [False, True],
                                  'context_length': 67584, 'max_context_length': 524288},
             ['Images', 'Tools', '68K context']),
            ('lm studio not loaded', {'supports': {'vision': True, 'tools': True}, 'max_context_length': 262144},
             ['Images', 'Tools', '262K context max']),
            ('lm studio advice', {'supports': {'vision': False, 'tools': False}, 'advisory': ['tools']},
             ['No images', 'Not trained for tools']),
            ('lm studio silent', {'details': {'format': 'gguf'}}, []),
            ('openrouter priced', PRICED,
             ['$0.075 / $0.30 per 1M tokens', 'Images', 'Tools', 'Thinking', '262K context']),
            ('openrouter free', {'capabilities': ['completion', 'tools'], 'context_length': 1000000,
                                 'pricing': {'prompt': '0', 'completion': '0'}},
             ['Free', 'No images', 'Tools', 'No thinking', '1M context']),
            # The levels a host's API accepts are not a statement about the model.
            ('generic host', {'thinking_levels': ['low', 'medium', 'high']}, []), ('no details', None, []), ('not details', ['vision'], []),
            ('sizes that are not sizes', {'context_length': True, 'max_context_length': '4096'}, []),
            # Advice applies to the capability it names, and only where the answer was no.
            ('advice about a capability it has', {'supports': {'tools': True}, 'advisory': ['tools']}, ['Tools']),
            ('advice about another', {'supports': {'vision': False}, 'advisory': ['vision']}, ['No images']),
        )
        for name, details, parts in cases:
            with self.subTest(model=name):
                self.assertEqual(summary_parts(details), parts)


class OllamaTests(unittest.TestCase):
    def show(self, payload):
        fixture = Server('json')
        self.addCleanup(fixture.close)
        fixture.server.payload = payload
        return OllamaProvider(fixture.host).show_model('gemma3:4b')

    def test_context_length_is_read_from_under_the_architecture(self):
        details = self.show(SHOW)
        self.assertEqual(details['context_length'], 131072)
        self.assertEqual({key: value for key, value in details.items() if key != 'context_length'}, SHOW)
        self.assertEqual(summary_parts(details), ['Images', 'Tools', 'No thinking', '131K context'])

    def test_context_length_falls_back_to_the_only_such_key_or_is_left_out(self):
        def info(**entries):
            return dict(SHOW, model_info={key.replace('__', '.'): value for key, value in entries.items()})
        other = info(general__architecture='clip', llama__context_length=4096)
        self.assertEqual(self.show(other)['context_length'], 4096)
        self.assertEqual(self.show(info(llama__context_length=2048))['context_length'], 2048)
        named = info(general__architecture='llama', llama__context_length=8192, clip__context_length=77)
        self.assertEqual(self.show(named)['context_length'], 8192)
        for silent in (info(general__architecture='x', a__context_length=1, b__context_length=2),
                       info(general__architecture='llama', llama__context_length='4096'),
                       info(llama__context_length=0), info(llama__context_length=True),
                       dict(SHOW, model_info=None), {'capabilities': ['completion']}):
            with self.subTest(details=silent):
                self.assertEqual(self.show(silent), silent)


class LMStudioTests(Loopback, unittest.TestCase):
    def test_no_training_for_tools_is_marked_as_advice(self):
        show = self.provider().show_model
        k2 = show(K2)
        self.assertEqual((k2['supports'], k2['advisory']), ({'vision': False, 'tools': False, 'thinking': True}, ['tools']))
        # The answer other code reads is unchanged; only the wording follows the mark.
        self.assertEqual((supports(k2, 'tools'), advisory(k2, 'tools'), advisory(k2, 'vision')), (False, True, False))
        self.assertEqual(summary_parts(k2), ['No images', 'Not trained for tools', 'Thinking', '68K context'])
        gemma = show(GEMMA)
        self.assertNotIn('advisory', gemma)
        self.assertEqual(summary_parts(gemma), ['Images', 'Tools', 'Thinking', '262K context max'])
        del self.entry(K2)['capabilities']
        self.assertEqual(summary_parts(dict(show(K2), context_length=None, max_context_length=None)), [])
        self.assertFalse(advisory(None, 'tools') or advisory({'advisory': 'tools'}, 'tool'))


