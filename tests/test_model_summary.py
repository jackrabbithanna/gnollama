@unittest.skipUnless(Gdk.Display.get_default(), 'GTK smoke tests require a display')
class WidgetTests(unittest.TestCase):
    setUp = test_ui.UITests.setUp
    tearDown = test_ui.UITests.tearDown
    make_tab = test_ui.UITests.make_tab

    def composer(self):
        widget = test_ui.ChatInput()
        widget.services = self.context.services
        return widget

    def shown(self, widget):
        return widget.model_summary.get_text() if widget.model_summary_cell.get_visible() else None

    def test_summary_is_text_shown_only_when_there_is_something_to_say(self):
        widget = self.composer()
        self.assertIsNone(self.shown(widget))
        widget.set_model_details(PRICED)
        self.assertEqual(self.shown(widget), '$0.075 / $0.30 per 1M tokens · Images · Tools · Thinking · 262K context')
        # Words a screen reader reads, beside the selector they describe; the tooltip says what the prices are.
        self.assertIsInstance(widget.model_summary, Gtk.Label)
        self.assertIs(widget.model_summary_cell, widget.connection_box.get_last_child())
        self.assertTrue(widget.model_dropdown.is_ancestor(widget.connection_box.get_first_child()))
        self.assertIn('per million tokens', widget.model_summary.get_tooltip_text())
        widget.set_model_details(PRICED, loading=True)
        self.assertIsNone(self.shown(widget))
        widget.set_model_details({'capabilities': ['completion']})
        self.assertEqual(self.shown(widget), 'No images · No tools · No thinking')
        self.assertIsNone(widget.model_summary.get_tooltip_text())
        for silent in ({}, None, {'details': {'family': 'llama'}}):
            widget.set_model_details(silent)
            self.assertIsNone(self.shown(widget))
            self.assertEqual(widget.model_summary.get_text(), '')

    def test_summary_follows_the_selected_model_and_is_empty_while_details_load(self):
        details = {'test': PRICED, 'zplain': {'capabilities': ['completion'], 'context_length': 8192}, 'zsilent': {}}
        with provider_patch('list_models', return_value=list(details)), \
                provider_patch('show_model', side_effect=lambda host, name, **kw: details[name]):
            tab = self.make_tab()
            composer = tab.chat_input
            self.assertTrue(self.shown(composer).startswith('$0.075 / $0.30 per 1M tokens'))
            composer.select_model('zplain')
            # Asked for, not yet answered.
            self.assertTrue(composer.capabilities_loading)
            self.assertIsNone(self.shown(composer))
            wait_for_model(tab, 'zplain')
            self.assertEqual(self.shown(composer), 'No images · No tools · No thinking · 8K context')
            # What is stored and sent is still the model's name.
            self.assertEqual(composer.get_selected_model(), 'zplain')
            composer.select_model('zsilent')
            wait_for_model(tab, 'zsilent')
            self.assertIsNone(self.shown(composer))
            composer.fetch_models(None)
            self.assertIsNone(self.shown(composer))

    def test_summary_wraps_and_never_widens_the_composer(self):
        widget = self.composer()
        box, across, down = widget.connection_box, Gtk.Orientation.HORIZONTAL, Gtk.Orientation.VERTICAL
        bare = (widget.measure(across, -1).minimum, box.measure(down, 200).natural)
        widget.set_model_details(dict(PRICED, pricing={'prompt': '0.0000123456', 'completion': '0.0000654321'}))
        self.assertEqual(widget.measure(across, -1).minimum, bare[0])
        # Narrow, the line goes below the selectors and breaks; wide, it is one line beside them.
        self.assertGreater(box.measure(down, 200).natural, bare[1])
        label = widget.model_summary
        self.assertGreater(label.measure(down, 120).natural, label.measure(down, 2000).natural)
        self.assertLess(label.measure(across, -1).minimum, 120)

    def test_notice_keeps_what_stops_a_send_and_the_button_says_why_it_is_off(self):
        widget = self.composer()
        widget.set_models(['test'])
        pump_until(lambda: not widget.capabilities_loading and self.context.services.idle)

        def said():
            return (widget.capability_notice.get_text() if widget.capability_notice.get_visible() else None,
                    widget.attach_button.get_sensitive(), widget.attach_button.get_tooltip_text())
        widget.set_model_details({'capabilities': ['completion']})
        self.assertEqual(said(), (None, False, 'This model does not support images.'))
        widget.restored_images = ['aW1hZ2U=']
        widget.update_capability_controls()
        self.assertEqual(said()[0], 'This model does not support images. Remove draft images or select a vision model to send.')
        self.assertFalse(widget.send_button.get_sensitive())
        widget.restored_images, widget.has_history_images = [], True
        widget.update_capability_controls()
        self.assertEqual(said()[0], 'This model does not support images. '
                                    'Earlier images remain saved; only text history will be sent.')
        widget.set_model_details({'capabilities': ['vision']})
        self.assertEqual(said(), (None, True, 'Attach Image'))
        widget.set_model_details(None)
        self.assertEqual(said(), (None, True, 'Attach Image'))
        widget.set_model_details(None, loading=True)
        self.assertEqual(said(), ('Checking image support…', False, 'Attach Image'))
        widget.set_model_details(None)
        widget.set_unavailable('Not here.')
        self.assertEqual(said()[0], 'Not here.')

    def test_target_pickers_show_the_summary_and_the_shared_composer_does_not(self):
        from src.widgets.comparison_view import ComparisonTab
        from src.widgets.model_target import TargetPicker
        with provider_patch('show_model', return_value=PRICED):
            for participant in (False, True):
                with self.subTest(participant=participant):
                    picker = TargetPicker(self.context, lambda *args: None, participant=participant)
                    self.addCleanup(picker.close)
                    pump_until(lambda: picker.input.get_selected_model() and not picker.input.capabilities_loading)
                    self.assertTrue(self.shown(picker.input).endswith('262K context'))
                    # In the picker's own wrapping row, which may be as narrow as a comparison column.
                    self.assertIs(picker.input.connection_box.get_parent(), picker)
                    self.assertLess(picker.measure(Gtk.Orientation.HORIZONTAL, -1).minimum, 360)
            tab = ComparisonTab(self.context)
            self.tabs.append(tab)
            pump_until(lambda: all(p.input.get_selected_model() and not p.input.capabilities_loading for p in tab.targets))
            self.assertTrue(all(self.shown(p.input) for p in tab.targets))
            # Its model is chosen per target, so its own selector and summary are not shown.
            self.assertFalse(tab.chat_input.connection_box.get_visible())


class Dialog:
    """The model details dialog filled from given details, as its titled fields."""
    def fields(self, show):
        from src.model_manager import ModelDetailsView, ModelManagerDialog
        view = ModelDetailsView('model')
        ModelManagerDialog.populate_model_details(None, view, copy.deepcopy(show), {'name': 'model'})
        found, box = {}, view.main_box.get_first_child()
        while box:
            title, card = box.get_first_child(), box.get_last_child()
            if isinstance(title, Gtk.Label):
                found[title.get_text()] = card.get_first_child().get_text()
            box = box.get_next_sibling()
        return found


@unittest.skipUnless(Gdk.Display.get_default(), 'GTK smoke tests require a display')
class DetailsDialogTests(Dialog, unittest.TestCase):
    def test_prices_are_shown_per_million_with_when_they_were_read(self):
        fields = self.fields(PRICED)
        self.assertEqual(fields['Pricing'], 'Prompt: $0.075 per 1M tokens\nCompletion: $0.30 per 1M tokens\n'
                                            'Cache read: $0.015 per 1M tokens\n' + NOTE)
        self.assertEqual(self.fields({'pricing': {'prompt': '0', 'completion': '0'}})['Pricing'], 'Free\n' + NOTE)
        for unpriced in ({'capabilities': ['completion']}, SHOW, {'pricing': {'prompt': 'soon'}}, {'pricing': {}}):
            with self.subTest(details=unpriced):
                self.assertNotIn('Pricing', self.fields(unpriced))

    def test_ollama_details_gain_only_the_context_length(self):
        fields = self.fields(dict(SHOW, context_length=131072))
        self.assertEqual(fields['Context Length'], '131072')
        self.assertEqual([name for name in fields if 'context' in name.lower()], ['Context Length'])
        self.assertEqual(fields['Capabilities'], '[\n  "completion",\n  "vision",\n  "tools"\n]')


